export type IconName = keyof typeof G;

export function Icon({
  name,
  size = 20,
  stroke = 1.6,
  dotColor,
  className,
  style,
  title,
}: {
  name: IconName;
  size?: number;
  stroke?: number;
  /** Colors the device's signature dot (its voice). */
  dotColor?: string;
  className?: string;
  style?: CSSProperties;
  title?: string;
}) {
  const g = G[name] ?? G.info!;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={stroke}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={style}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {g.d.map((d) => (
        <path key={d} d={d} />
      ))}
      {g.dots?.map(([cx, cy, r]) => (
        <circle key={`${cx}-${cy}`} cx={cx} cy={cy} r={r} fill={dotColor ?? "currentColor"} stroke="none" />
      ))}
    </svg>
  );
}

export function deviceIcon(kind: DeviceKind): IconName {
  switch (kind) {
    case "desktop":
      return "desktop";
    case "laptop":
      return "laptop";
    case "phone":
      return "phone";
    case "tablet":
      return "tablet";
    case "accessory":
      return "accessory";
    default:
      return "monitor";
  }
}

